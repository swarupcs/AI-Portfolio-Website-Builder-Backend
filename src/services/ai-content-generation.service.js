// Validation functions
const validatePortfolioContent = (content) => {
  const required = ['hero', 'about', 'services', 'contact'];

  for (const section of required) {
    if (!content[section]) {
      throw new Error(`Missing required section: ${section}`);
    }
  }

  // Validate hero section
  if (!content.hero.headline || !content.hero.subheading || !content.hero.cta) {
    throw new Error('Hero section missing required fields');
  }

  // Validate about section
  if (!content.about.introduction || !Array.isArray(content.about.highlights)) {
    throw new Error('About section missing required fields');
  }

  // Validate services
  if (!Array.isArray(content.services) || content.services.length === 0) {
    throw new Error('Services section must be a non-empty array');
  }

  content.services.forEach((service, index) => {
    if (!service.title || !service.description || !service.icon) {
      throw new Error(`Service ${index} missing required fields`);
    }
  });

  // Validate contact
  if (!content.contact.cta || !content.contact.description) {
    throw new Error('Contact section missing required fields');
  }
};

const validateProjectContent = (project) => {
  const required = ['name', 'tagline', 'description', 'challenge', 'solution'];

  for (const field of required) {
    if (!project[field]) {
      throw new Error(`Project missing required field: ${field}`);
    }
  }

  if (!Array.isArray(project.technologies)) {
    throw new Error('Technologies must be an array');
  }

  if (!Array.isArray(project.features)) {
    throw new Error('Features must be an array');
  }

  if (!Array.isArray(project.metrics)) {
    throw new Error('Metrics must be an array');
  }
};

// Helper function to create project enhancement prompt
const createProjectEnhancementPrompt = (project, analysisContext) => {
  return `
Enhance this ${analysisContext.roleType} project for a portfolio:

Project Details:
- Name: ${project.name || 'Unnamed Project'}
- Description: ${project.description || 'No description available'}
- Technologies: ${(project.technologies || []).join(', ') || 'Not specified'}
- URL: ${project.url || 'Not available'}
- GitHub: ${project.github || 'Not available'}

Context:
- Professional Level: ${analysisContext.experienceLevel}
- Industry: ${analysisContext.industries?.join(', ') || 'General'}
- Role Focus: ${analysisContext.roleType}

Make the project sound impressive and results-focused. Include specific technical achievements and business impact where possible.
`;
};

// Rate limiting and retry logic
const withRetry = async (fn, maxRetries = 3, baseDelay = 1000) => {
  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    try {
      return await fn();
    } catch (error) {
      if (attempt === maxRetries) {
        throw error;
      }

      // Check if it's a rate limit error
      if (error.status === 429 || error.code === 'rate_limit_exceeded') {
        const delay = baseDelay * Math.pow(2, attempt - 1); // Exponential backoff
        console.warn(
          `Rate limited, retrying in ${delay}ms (attempt ${attempt}/${maxRetries})`
        );
        await new Promise((resolve) => setTimeout(resolve, delay));
      } else {
        throw error; // Don't retry non-rate-limit errors
      }
    }
  }
};

// Export service with retry wrapper
export const aiService = {
  generatePortfolioContent: (prompt) =>
    withRetry(() => generatePortfolioContent(prompt)),
  enhanceProject: (prompt) => withRetry(() => enhanceProject(prompt)),
  enhanceProjectsBatch,
  generateProfessionalSummary: (resumeData, context) =>
    withRetry(() => generateProfessionalSummary(resumeData, context)),
  generateSEOContent: (portfolioData) =>
    withRetry(() => generateSEOContent(portfolioData)),
};
