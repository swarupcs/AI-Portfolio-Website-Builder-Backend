// Generate multiple project enhancements in batch
export const enhanceProjectsBatch = async (projects, analysisContext) => {
  const enhancedProjects = [];
  const errors = [];

  // Process projects in batches to avoid rate limits
  const batchSize = 3;

  for (let i = 0; i < projects.length; i += batchSize) {
    const batch = projects.slice(i, i + batchSize);
    const batchPromises = batch.map(async (project, index) => {
      try {
        const prompt = createProjectEnhancementPrompt(project, analysisContext);
        return await enhanceProject(prompt);
      } catch (error) {
        console.error(`Failed to enhance project ${project.name}:`, error);
        errors.push({ project: project.name, error: error.message });
        return null;
      }
    });

    const batchResults = await Promise.all(batchPromises);
    enhancedProjects.push(...batchResults.filter(Boolean));

    // Add delay between batches to avoid rate limiting
    if (i + batchSize < projects.length) {
      await new Promise((resolve) => setTimeout(resolve, 1000));
    }
  }

  return {
    enhanced: enhancedProjects,
    errors: errors,
  };
};

// Generate professional summary for about section
export const generateProfessionalSummary = async (
  resumeData,
  analysisContext
) => {
  try {
    const prompt = `
Generate a professional summary for a ${analysisContext.roleType} with ${
      analysisContext.experienceLevel
    } experience.

Background:
- Name: ${resumeData.personalInfo?.name || 'Professional'}
- Experience: ${analysisContext.totalExperience} positions
- Projects: ${analysisContext.totalProjects} projects
- Key Skills: ${analysisContext.skills.slice(0, 5).join(', ')}
- Industries: ${analysisContext.industries.join(', ')}

Generate a compelling professional summary (2-3 sentences) that highlights expertise, experience, and value proposition.
Return only the summary text, no JSON or formatting.
`;

    const completion = await openai.chat.completions.create({
      model: AI_CONFIG.model,
      max_tokens: 200,
      temperature: 0.7,
      messages: [
        {
          role: 'user',
          content: prompt,
        },
      ],
    });

    const summary = completion.choices[0]?.message?.content?.trim();

    if (!summary) {
      throw new Error('No summary generated');
    }

    return summary;
  } catch (error) {
    console.error('Failed to generate professional summary:', error);
    throw error;
  }
};

