import OpenAI from 'openai';

// Initialize OpenAI client
const openai = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY,
});

// Configuration
const AI_CONFIG = {
  model: 'gpt-4o-mini', // Fast and cost-effective model
  maxTokens: 2000,
  temperature: 0.7,
  timeout: 20000, // 20 second timeout
};

// Generate portfolio content using AI
export const generatePortfolioContent = async (prompt) => {
  try {
    console.log('🤖 Generating portfolio content with AI...');

    const systemPrompt = `You are a professional portfolio website content generator. Generate high-quality, engaging, and professional content for portfolio websites. Always return valid JSON format with the exact structure requested. Be creative but professional, and tailor content to the specific role and experience level.`;

    const completion = await openai.chat.completions.create({
      model: AI_CONFIG.model,
      max_tokens: AI_CONFIG.maxTokens,
      temperature: AI_CONFIG.temperature,
      timeout: AI_CONFIG.timeout,
      messages: [
        {
          role: 'system',
          content: systemPrompt,
        },
        {
          role: 'user',
          content: `${prompt}\n\nReturn JSON with this exact structure:
{
  "hero": {
    "headline": "string",
    "subheading": "string", 
    "cta": "string"
  },
  "about": {
    "introduction": "string (2-3 sentences)",
    "highlights": ["string", "string", "string"]
  },
  "services": [
    {
      "title": "string",
      "description": "string",
      "icon": "string"
    }
  ],
  "contact": {
    "cta": "string",
    "description": "string"
  }
}`,
        },
      ],
    });

    const content = completion.choices[0]?.message?.content;

    if (!content) {
      throw new Error('No content generated by AI');
    }

    // Parse and validate JSON response
    const parsedContent = JSON.parse(content);

    // Validate structure
    validatePortfolioContent(parsedContent);

    console.log('✅ Portfolio content generated successfully');
    return parsedContent;
  } catch (error) {
    console.error('AI portfolio content generation failed:', error);

    // If JSON parsing fails, try to extract JSON from response
    if (error instanceof SyntaxError && error.message.includes('JSON')) {
      try {
        const content = completion?.choices[0]?.message?.content;
        const jsonMatch = content.match(/\{[\s\S]*\}/);
        if (jsonMatch) {
          const extractedJson = JSON.parse(jsonMatch[0]);
          validatePortfolioContent(extractedJson);
          return extractedJson;
        }
      } catch (extractError) {
        console.error('Failed to extract JSON from AI response:', extractError);
      }
    }

    throw new Error(`AI content generation failed: ${error.message}`);
  }
};

